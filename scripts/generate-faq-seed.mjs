import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { faqSeedItems } from '../data/faq.ts'
import { validateFaqInput } from '../shared/faq-validation.ts'

// UUID v5 in the standard URL namespace; independent of content edits/order.
const namespace = Buffer.from('6ba7b8119dad11d180b400c04fd430c8', 'hex')
const seedId = (legacyId) => {
  const bytes = createHash('sha1').update(namespace).update(`cp-department/faq/${legacyId}`).digest().subarray(0, 16)
  bytes[6] = (bytes[6] & 0x0f) | 0x50
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = bytes.toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
const quote = value => `'${value.replaceAll("'", "''")}'`
const ids = new Set()
const rows = faqSeedItems.map(({ id, ...input }, index) => {
  if (ids.has(id)) throw new Error(`Duplicate seed ID: ${id}`)
  ids.add(id)
  const faq = validateFaqInput(input)
  return `  (${index + 1}, ${quote(seedId(id))}::uuid, ${quote(faq.category)}, ${quote(faq.question)}, ${quote(faq.answer)})`
})
const sql = `-- Generated by npm run faq:seed:sql from data/faq.ts. Do not edit this file.
-- Initial import only. Supabase is the live source of truth after setup.
-- Re-running skips existing seed IDs without overwriting their content.
-- Run only for initial setup: re-running can restore seed entries deleted later.
begin;
set local standard_conforming_strings = on;
insert into public.faqs (id, category, question, answer)
select id, category, question, answer
from (values
${rows.join(',\n')}
) as seed(position, id, category, question, answer)
order by position
on conflict (id) do nothing;
commit;
`
await writeFile(new URL('../supabase/seed.sql', import.meta.url), sql, 'utf8')
console.log(`Prepared ${rows.length} FAQ entries in supabase/seed.sql. No database connection was made.`)
